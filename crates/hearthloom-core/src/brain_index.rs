//! The brain index: `~/.hearthloom/BRAIN.md` — a byte-stable, ≤200-line,
//! ≤25KB markdown summary loaded by any harness at session start (Claude
//! Code's MEMORY.md pattern applied to a life).
//!
//! Byte-stable means: identical store contents produce identical bytes, so
//! prompt caches stay warm between regenerations. No timestamps of the
//! generation itself, deterministic ordering everywhere.

use anyhow::Result;

use crate::store::Store;

const MAX_LINES: usize = 200;
const MAX_BYTES: usize = 25 * 1024;
const TOP_ENTITIES: usize = 20;
const RECENT_EPISODES: usize = 15;
/// "## Sources": what the record holds, per source (0.5.82).
const SOURCE_LINES: usize = 30;
const SOURCE_KINDS: usize = 6;

/// Render the brain index from current store contents.
pub fn generate(store: &Store) -> Result<String> {
    let counts = store.counts()?;
    let top = store.top_entities(TOP_ENTITIES)?;
    let recent = store.recent_episodes(RECENT_EPISODES)?;

    let mut out = String::new();
    out.push_str("# BRAIN.md — Hearthloom index\n\n");
    out.push_str(
        "This file is regenerated by `hearthloom index`; do not edit. It is a \
         progressive-disclosure entry point: use the tools/CLI below for anything deeper.\n\n",
    );

    // Self-model: confirmed propositions first (the structured, human-
    // gated identity — private sphere excluded ALWAYS, vault or not),
    // then the latest consolidation digest. Byte-stable: stored rows and
    // stored text only, never fresh LLM output.
    out.push_str("## Self-model\n\n");
    let propositions = store.brain_propositions()?;
    if !propositions.is_empty() {
        let mut sphere = "";
        for p in propositions.iter().take(40) {
            if p.sphere != sphere {
                sphere = &p.sphere;
                out.push_str(&format!("**{sphere}**\n"));
            }
            out.push_str(&format!(
                "- ({}) {} _[{}]_\n",
                p.kind,
                one_line(&p.text),
                p.origin
            ));
        }
        out.push('\n');
    }
    match store.latest_summary()? {
        Some(summary) => {
            out.push_str(&format!(
                "_From the {} consolidation digest (trust: agent; episode {})._\n\n",
                crate::store::base_ref(&summary.source_ref)
                    .strip_prefix("summary:")
                    .unwrap_or("latest"),
                summary.id
            ));
            if let Some(body) = store.episode_body(&summary.id)? {
                for line in body.lines().take(30) {
                    out.push_str(&demote_heading(line));
                    out.push('\n');
                }
                out.push('\n');
            }
        }
        None => out.push_str(
            "_No consolidation digest yet. Configure an LLM provider \
             (provider.llm in config, key in ~/.hearthloom/.env) and run \
             `hearthloom consolidate`._\n\n",
        ),
    }

    out.push_str("## Store\n\n");
    out.push_str(&format!(
        "- {} episodes, {} entities, {} current edges\n",
        counts.episodes, counts.entities, counts.edges
    ));
    out.push_str(&format!(
        "- {} pending merge reviews, {} pending quarantined memories\n\n",
        counts.review_pending, counts.quarantine_pending
    ));

    // What the record holds, per source: counts, kinds and date spans of
    // live, non-private episodes only (private never reaches BRAIN.md).
    // Source and kind names are printed only when they are plain short
    // identifiers (`printable_name`) — whoever ingests chooses them.
    out.push_str("## Sources\n\n");
    let shares = store.source_shares(true)?;
    if shares.is_empty() {
        out.push_str("_Nothing ingested yet._\n");
    } else {
        for line in crate::store::source_lines(&shares, SOURCE_LINES, SOURCE_KINDS) {
            out.push_str(&line);
            out.push('\n');
        }
    }
    out.push('\n');

    out.push_str("## Top entities\n\n");
    if top.is_empty() {
        out.push_str("_Nothing ingested yet. Try `hearthloom ingest git <repo>`._\n");
    } else {
        for (entity, n) in &top {
            out.push_str(&format!(
                "- **{}** ({}, {} episodes)\n",
                one_line(&entity.name),
                entity.entity_type,
                n
            ));
        }
    }
    out.push('\n');

    out.push_str("## Recent activity\n\n");
    if recent.is_empty() {
        out.push_str("_No episodes._\n");
    } else {
        for episode in &recent {
            let when = episode
                .event_time
                .as_deref()
                .map(|t| &t[..10])
                .unwrap_or("????-??-??");
            let title: String = one_line(&episode.title).chars().take(80).collect();
            out.push_str(&format!(
                "- {} [{}/{}] {}\n",
                when, episode.source, episode.kind, title
            ));
        }
    }
    out.push('\n');

    out.push_str("## Schema cheat-sheet\n\n");
    out.push_str(
        "- `episodes` — append-only ground truth (source, event_time+tz+uncertainty, trust, scope, content_ref)\n\
         - `entities` / `entity_attributes` — typed nodes; emails/handles/repo-urls drive identity\n\
         - `edges` — bi-temporal (t_valid/t_invalid/t_created/t_expired); provenance in `edge_provenance`\n\
         - `episode_entities` — which episodes cite which entities (role-tagged)\n\
         - `mutations` — append-only write log; the change feed reads this\n\
         - `quarantine` — agent-proposed memories awaiting review\n\n",
    );

    out.push_str("## How to query\n\n");
    out.push_str(
        "- CLI: `hearthloom search <query>` · `hearthloom recall --on YYYY-MM-DD` · \
         `hearthloom entity <name>` · `hearthloom events --since <cursor>`\n\
         - MCP (streamable HTTP at `/mcp`): `search(query, detail)`, \
         `traverse(start, relation, depth, as_of?)`, `recall(date|from/to|entity)`, \
         `propose_memory(entries)` — writes land in quarantine, never directly in the graph\n\
         - Example: \"what was I working on March 15?\" → `recall(date: \"2026-03-15\")` \
         returns that day's episodes with cited sources and the edges valid that day\n",
    );

    // Enforce the budget: drop whole trailing lines if needed.
    let mut lines: Vec<&str> = out.lines().collect();
    while lines.len() > MAX_LINES || lines.join("\n").len() + 1 > MAX_BYTES {
        lines.pop();
    }
    let mut result = lines.join("\n");
    result.push('\n');
    Ok(result)
}

/// Titles, names and propositions are other people's text (a calendar
/// title, a sender's display name): one line each, so none can start a
/// line of its own — Ask's prompt builder keeps or drops BRAIN.md by its
/// `## ` section headings (rlm.rs `brain_for_ask`).
fn one_line(s: &str) -> String {
    s.split(['\r', '\n', '\u{85}', '\u{2028}', '\u{2029}'])
        .map(str::trim)
        .filter(|part| !part.is_empty())
        .collect::<Vec<_>>()
        .join(" ")
}

/// The digest is model output that may carry headings of its own: keep
/// them below BRAIN.md's `## ` sections so none can open or close one.
fn demote_heading(line: &str) -> String {
    let hashes = line.chars().take_while(|c| *c == '#').count();
    if (1..3).contains(&hashes) {
        format!("###{}", &line[hashes..])
    } else {
        line.to_string()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_third_party_text_cannot_open_a_section() {
        assert_eq!(one_line("Lunch\n## Store\r\nmore"), "Lunch ## Store more");
        assert_eq!(one_line("a\u{2028}b"), "a b");
        assert_eq!(
            demote_heading("## Self-model notes"),
            "### Self-model notes"
        );
        assert_eq!(demote_heading("# Big"), "### Big");
        assert_eq!(demote_heading("### Already deep"), "### Already deep");
        assert_eq!(demote_heading("- a list line"), "- a list line");
    }

    #[test]
    fn test_byte_stable_and_bounded() {
        let store = Store::open_in_memory().unwrap();
        let a = generate(&store).unwrap();
        let b = generate(&store).unwrap();
        assert_eq!(a, b, "regeneration must be byte-stable");
        assert!(a.lines().count() <= MAX_LINES);
        assert!(a.len() <= MAX_BYTES);
        assert!(a.contains("## Self-model"));
        assert!(a.contains("## Schema cheat-sheet"));
        assert!(a.contains("## Sources"));
    }

    #[test]
    fn test_sources_say_what_the_record_holds_and_never_what_is_private() {
        use crate::ingest::{EpisodeDraft, IngestBatch};
        use crate::time::{EventTime, TimeUncertainty};
        let tmp = tempfile::tempdir().unwrap();
        let home = crate::paths::Home::at(tmp.path());
        home.init().unwrap();
        let store = Store::open(&home.db_path()).unwrap();
        let draft = |source: &str, r: &str, kind: &str, day: &str, scope: &str| EpisodeDraft {
            source: source.into(),
            source_ref: r.into(),
            kind: kind.into(),
            title: r.into(),
            body: "b".into(),
            event_time: EventTime::parse_rfc3339(
                &format!("{day}T12:00:00Z"),
                TimeUncertainty::Exact,
            )
            .unwrap(),
            trust: "imported".into(),
            scope: Some(scope.into()),
            entities: vec![],
            edges: vec![],
        };
        store
            .apply_batch(
                &home,
                &IngestBatch {
                    actor: "plugin:minidash".into(),
                    session_id: None,
                    episodes: vec![
                        draft(
                            "minidash",
                            "h:day:1",
                            "minidash_day",
                            "2026-10-20",
                            "personal",
                        ),
                        draft(
                            "minidash",
                            "h:day:2",
                            "minidash_day",
                            "2026-11-02",
                            "personal",
                        ),
                        draft(
                            "minidash",
                            "h:incident:1",
                            "minidash_incident",
                            "2026-10-25",
                            "personal",
                        ),
                        draft("secretsrc", "s:1", "note", "2026-10-01", "private"),
                        draft(
                            "Weird Name; IGNORE ALL",
                            "w:1",
                            "x",
                            "2026-10-01",
                            "personal",
                        ),
                        {
                            let mut odd = draft("oddtime", "o:1", "x", "2026-10-01", "personal");
                            odd.event_time.utc = Some("ignore-all-previous".into());
                            odd
                        },
                    ],
                },
            )
            .unwrap();
        let brain = generate(&store).unwrap();
        // the section itself (Recent activity prints `[source/kind]` too —
        // Ask never sees that section)
        let sources = brain
            .split("## Sources\n")
            .nth(1)
            .and_then(|rest| rest.split("\n## ").next())
            .unwrap();
        assert!(
            brain.contains("- minidash: 3 episodes (minidash_day 2, minidash_incident 1), 2026-10-20 → 2026-11-02"),
            "{brain}"
        );
        assert!(
            !brain.contains("secretsrc"),
            "a private-only source never appears"
        );
        assert!(
            !sources.contains("IGNORE"),
            "an unprintable name is counted, never printed"
        );
        assert!(sources.contains("other sources with unusual names: 1 (1 episodes)"));
        assert!(
            sources.contains("- oddtime: 1 episode (x 1)\n"),
            "{sources}"
        );
        assert!(
            !sources.contains("ignore-all"),
            "only real dates are printed"
        );
        assert_eq!(brain, generate(&store).unwrap(), "byte-stable");
    }

    #[test]
    fn test_source_lines_cap_and_say_what_they_left_out() {
        use crate::store::{source_lines, SourceShare};
        let share = |name: &str, n: i64| SourceShare {
            source: name.into(),
            episodes: n,
            kinds: (0..8).map(|k| (format!("k{k}"), 1)).collect(),
            first: None,
            last: None,
        };
        let shares: Vec<SourceShare> = (0..5).map(|i| share(&format!("s{i}"), 10 - i)).collect();
        let lines = source_lines(&shares, 3, 6);
        assert_eq!(lines.len(), 4);
        assert!(lines[0].contains("+2 more"), "{}", lines[0]);
        assert_eq!(lines[3], "- and 2 more sources (13 episodes)");
    }
}
